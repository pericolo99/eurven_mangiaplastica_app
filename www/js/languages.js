$$(document).on('click','.change-lang', function (e) {
    lang = $$(this).data('lang');
    myApp.changeLang(lang);
    myApp.views.main.router.refreshPage()

});

myApp.changeLang = function(lg) {
    myApp.lang = app_langs[lg];
    myApp.language = lg;
    myApp.storeSingleData(myApp.storedKey.LANGUAGE, lg);
    myApp.views.main.router.clearPreviousHistory(true);

}
myApp.translate = function(key) {

    if (myApp.lang == null) {

        myApp.lang = app_langs[myApp.language];
    }


    if (myApp.lang[key])
            return myApp.lang[key];
    else
        return key;
}



$$(document).on('click','.select-lang', function (e) {


    var buttons = [];

    Object.keys(active_langs).forEach(function(key) {

        if (myApp.language != null && key != myApp.language) {
            b = {};
            b.text = active_langs[key];
            b.onClick = function () {
                myApp.changeLang(key);
                myApp.views.main.router.refreshPage()
            };
            buttons.push(b);
        }

    })

    buttons.push( {text: myApp.translate("button_annulla"), color: "black"});


    myApp.dialog.create({
        title: myApp.translate('menu_lingua'),
        buttons: buttons,
        verticalButtons: true,
    }).open();


});
