export const availableLocales = [
  { code: 'it', label: 'Italiano' },
  { code: 'en', label: 'English' },
]

const state = reactive({
  locale: localStorage.getItem(STORAGE_KEY) || 'it',
})

function resolve(obj, path) {
  return path.split('.').reduce((acc, k) => (acc == null ? undefined : acc[k]), obj)
}

export function t(key) {
  const dict = messages[state.locale] || messages.it
  const val = resolve(dict, key)
  if (val !== undefined) return val
  const fallback = resolve(messages.it, key)
  return fallback !== undefined ? fallback : key
}

export function setLocale(code) {
  if (!messages[code]) return
  state.locale = code
  localStorage.setItem(STORAGE_KEY, code)
}

export const locale = computed(() => state.locale)

// Plugin Vue: espone $t e <i18n> reattivo
export const i18n = {
  install(app) {
    app.config.globalProperties.$t = t
    app.provide('i18n', { t, setLocale, locale, availableLocales })
  },
}

export function useI18n() {
  return { t, setLocale, locale, availableLocales }
}
